# Create a minimal 1x1 pixel transparent PNG icon
$png = @(
    0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A,  # PNG signature
    0x00, 0x00, 0x00, 0x0D,  # IHDR chunk size
    0x49, 0x48, 0x44, 0x52,  # IHDR chunk type
    0x00, 0x00, 0x00, 0x01,  # Width: 1
    0x00, 0x00, 0x00, 0x01,  # Height: 1
    0x08, 0x06, 0x00, 0x00, 0x00,  # Bit depth, color type, etc.
    0x1F, 0x15, 0xC4, 0x89,  # CRC for IHDR
    0x00, 0x00, 0x00, 0x0A,  # IDAT chunk size
    0x49, 0x44, 0x41, 0x54,  # IDAT chunk type
    0x78, 0x9C, 0x63, 0xF8, 0x0F, 0x00, 0x00, 0x01,
    0x01, 0x00, 0x00,
    0xAE, 0x7E, 0x34, 0xDE,  # CRC for IDAT
    0x00, 0x00, 0x00, 0x00,  # IEND chunk size
    0x49, 0x45, 0x4E, 0x44,  # IEND chunk type
    0xAE, 0x42, 0x60, 0x82   # CRC for IEND
)

[byte[]] $bytes = $png
[System.IO.File]::WriteAllBytes("icon.png", $bytes)

# Also create a minimal ICO file (1x1 transparent)
$ico = @(
    0x00, 0x00, 0x01, 0x00,  # ICO header
    0x01, 0x00,              # 1 image
    0x01, 0x01,              # 1x1 width/height  
    0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x18, 0x00,  # Color count, reserved, planes, bits per pixel
    0x30, 0x00, 0x00, 0x00,  # Image size (48 bytes)
    0x16, 0x00, 0x00, 0x00,  # Image offset (22 bytes)
    # BMP image data (48 bytes)
    0x28, 0x00, 0x00, 0x00,  # BMP header size (40)
    0x01, 0x00, 0x00, 0x00,  # Width: 1
    0x02, 0x00, 0x00, 0x00,  # Height: 2 (includes mask)
    0x01, 0x00, 0x18, 0x00,  # Planes, bits per pixel
    0x00, 0x00, 0x00, 0x00,  # Compression
    0x00, 0x00, 0x00, 0x00,  # Image size
    0x00, 0x00, 0x00, 0x00,  # X pixels per meter
    0x00, 0x00, 0x00, 0x00,  # Y pixels per meter
    0x00, 0x00, 0x00, 0x00,  # Colors used
    0x00, 0x00, 0x00, 0x00,  # Colors important
    # Image data (white pixel)
    0xFF, 0xFF, 0xFF,        # RGB white
    # Mask (transparent)
    0x00, 0x00, 0x00, 0x00   # Mask data
)

[byte[]] $bytes = $ico
[System.IO.File]::WriteAllBytes("icon.ico", $bytes)
